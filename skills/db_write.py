#!/usr/bin/env python3
"""Write to Kafka topics (annotations, decision_packet). Sink consumer persists to DB.

Usage:
    python skills/db_write.py '{"topic": "annotations", "payload": {"agent_id": "claude-code", "theme": "TSLA Q1"}}'
    python skills/db_write.py '{"topic": "decision_packet", "payload": {"agent_id": "claude-code", "signal": "bullish"}}'
"""
from __future__ import annotations

import json
import os
import sys
import copy
from pathlib import Path

import psycopg2
from confluent_kafka import Producer

# Also support loading this CLI by file path from local tools and test runners.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from evidence import build_snapshot, canonical_json, fetch_payloads, positive_ids

ALLOWED_TOPICS = {"annotations", "decision_packet"}

KAFKA_BOOTSTRAP = os.environ.get(
    "KAFKA_BOOTSTRAP", "localhost:9092,localhost:9093,localhost:9094"
)

DB_SETTINGS = {
    "host": os.environ.get("DB_HOST", "localhost"),
    "port": int(os.environ.get("DB_PORT", "5432")),
    "dbname": os.environ.get("DB_NAME", "bluesky"),
    "user": os.environ.get("DB_USER", "bluesky"),
    "password": os.environ.get("DB_PASSWORD", "bluesky"),
}


def validate_ticket_ids(ticket_ids: list[int]) -> tuple[list[int], list[int]]:
    """Check which attention_ticket_ids actually exist in DB. Returns (valid, invalid)."""
    ticket_ids = positive_ids(ticket_ids, "attention_ticket_ids", nonempty=False)
    if not ticket_ids:
        return [], []
    conn = psycopg2.connect(**DB_SETTINGS)
    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT id FROM attention_tickets WHERE id = ANY(%s)",
                (ticket_ids,),
            )
            found = {row[0] for row in cur.fetchall()}
    finally:
        conn.close()
    valid = [tid for tid in ticket_ids if tid in found]
    invalid = [tid for tid in ticket_ids if tid not in found]
    return valid, invalid


def validate_annotation_ids(annotation_ids: list[int]) -> tuple[list[int], list[int]]:
    """Check which annotation IDs actually exist in DB. Returns (valid, invalid)."""
    annotation_ids = positive_ids(annotation_ids, "related_annotations", nonempty=False)
    if not annotation_ids:
        return [], []
    conn = psycopg2.connect(**DB_SETTINGS)
    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT id FROM annotations WHERE id = ANY(%s)",
                (annotation_ids,),
            )
            found = {row[0] for row in cur.fetchall()}
    finally:
        conn.close()
    valid = [aid for aid in annotation_ids if aid in found]
    invalid = [aid for aid in annotation_ids if aid not in found]
    return valid, invalid


def prepare_payload(topic: str, payload: dict) -> dict:
    """Validate references and generate evidence before crossing Kafka's boundary."""
    if topic not in ALLOWED_TOPICS:
        raise ValueError(f"Topic '{topic}' not allowed. Use: {sorted(ALLOWED_TOPICS)}")
    if not isinstance(payload, dict) or not payload:
        raise ValueError("payload must be a non-empty JSON object")
    canonical_json(payload)  # Reject non-JSON/non-finite values before publishing.
    prepared = copy.deepcopy(payload)
    if topic == "annotations":
        if "attention_ticket_ids" in prepared:
            ticket_ids = positive_ids(prepared["attention_ticket_ids"], "attention_ticket_ids", nonempty=False)
            conn = psycopg2.connect(**DB_SETTINGS)
            try:
                with conn:
                    fetch_payloads(conn, "attention_tickets", ticket_ids)
            finally:
                conn.close()
        return prepared

    if "evidence_snapshot" in prepared:
        raise ValueError("evidence_snapshot is generated by the publisher and cannot be supplied")
    fa = prepared.get("framework_analysis")
    required_fa = [
        "traversability", "barbell_position", "moat",
        "cycle_position", "prohibitions_check", "technical_analysis",
    ]
    if not isinstance(fa, dict):
        raise ValueError("decision_packet requires framework_analysis")
    missing_fa = [field for field in required_fa if not fa.get(field)]
    if missing_fa:
        raise ValueError(f"decision_packet framework_analysis missing required fields: {missing_fa}")
    annotation_ids = positive_ids(prepared.get("related_annotations"), "related_annotations")
    conn = psycopg2.connect(**DB_SETTINGS)
    try:
        # All annotation, ticket, and original reads share one MVCC snapshot.
        conn.set_session(isolation_level="REPEATABLE READ", readonly=True)
        with conn:
            prepared["evidence_snapshot"] = build_snapshot(conn, annotation_ids)
            prepared["related_annotations"] = annotation_ids
    finally:
        conn.close()
    return prepared


def produce_message(topic: str, payload: dict) -> dict:
    if topic not in ALLOWED_TOPICS:
        raise ValueError(f"Topic '{topic}' not allowed. Use: {sorted(ALLOWED_TOPICS)}")

    producer = Producer({
        "bootstrap.servers": KAFKA_BOOTSTRAP,
        "acks": "all",
        "enable.idempotence": True,
        "compression.type": "zstd",
        "delivery.timeout.ms": 10000,
        "request.timeout.ms": 5000,
    })

    result = {"status": "pending"}
    delivery_error = [None]

    def on_delivery(err, msg):
        if err:
            delivery_error[0] = str(err)
            result["status"] = "error"
            result["error"] = str(err)
        else:
            result["status"] = "ok"
            result["topic"] = msg.topic()
            result["partition"] = msg.partition()
            result["offset"] = msg.offset()

    value = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    producer.produce(
        topic=topic,
        value=value,
        on_delivery=on_delivery,
    )
    remaining = producer.flush(timeout=12)

    if delivery_error[0]:
        raise RuntimeError(f"Kafka publication failed: {delivery_error[0]}")
    if remaining or result["status"] != "ok":
        raise TimeoutError("Kafka did not acknowledge the publication before its delivery deadline")

    return result


def main():
    if len(sys.argv) < 2:
        print(json.dumps({"error": "Usage: python db_write.py '<json_params>'"}))
        sys.exit(1)

    try:
        params = json.loads(sys.argv[1])
    except json.JSONDecodeError as e:
        print(json.dumps({"error": f"Invalid JSON: {e}"}))
        sys.exit(1)

    topic = params.get("topic", "")
    payload = params.get("payload", {})

    try:
        payload = prepare_payload(topic, payload)
        result = produce_message(topic, payload)
        print(json.dumps(result, ensure_ascii=False))
    except Exception as e:
        print(json.dumps({"error": str(e)}))
        sys.exit(1)


if __name__ == "__main__":
    main()
